// Helper to decode SVG generated by QRCodeSVG using jsQR
export function decodeQRCodeSVG(value, errorCorrectionLevel = 'M') {
  const svg = ReactDOMServer.renderToStaticMarkup(
    React.createElement(QRCodeSVG, {
      value,
      level: errorCorrectionLevel,
      includeMargin: true,
      size: 200,
    })
  );

  const vbMatch = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  if (!vbMatch) throw new Error('viewBox not found in QRCodeSVG output');
  const matrixSize = parseInt(vbMatch[1], 10);

  const grid = Array.from({ length: matrixSize }, () => new Array(matrixSize).fill(false));
  const pathMatch = svg.match(/<path[^>]+fill="#000000"[^>]+d="([^"]+)"/);
  if (!pathMatch) throw new Error('Dark module path not found in QRCodeSVG output');

  const d = pathMatch[1];
  const regex = /M(\d+)(?:,|\s+)(\d+)\s*h(\d+)v(\d+)/g;
  let match;
  while ((match = regex.exec(d)) !== null) {
    const startX = parseInt(match[1], 10);
    const startY = parseInt(match[2], 10);
    const w = parseInt(match[3], 10);
    const h = parseInt(match[4], 10);

    for (let y = startY; y < startY + h; y++) {
      for (let x = startX; x < startX + w; x++) {
        if (y < matrixSize && x < matrixSize) {
          grid[y][x] = true;
        }
      }
    }
  }

  const scale = 8;
  const imgWidth = matrixSize * scale;
  const imgHeight = matrixSize * scale;
  const rgba = new Uint8ClampedArray(imgWidth * imgHeight * 4);

  for (let gy = 0; gy < matrixSize; gy++) {
    for (let gx = 0; gx < matrixSize; gx++) {
      const isDark = grid[gy][gx];
      const color = isDark ? 0 : 255;
      for (let py = 0; py < scale; py++) {
        for (let px = 0; px < scale; px++) {
          const pixelX = gx * scale + px;
          const pixelY = gy * scale + py;
          const idx = (pixelY * imgWidth + pixelX) * 4;
          rgba[idx] = color;
          rgba[idx + 1] = color;
          rgba[idx + 2] = color;
          rgba[idx + 3] = 255;
        }
      }
    }
  }

  const code = jsQR(rgba, imgWidth, imgHeight);
  return code ? code.data : null;
}

async function request(url, options = {}) {
  const headers = { ...(options.headers || {}) };
  const res = await fetch(url, { ...options, headers });
  const cookies = res.headers.getSetCookie ? res.headers.getSetCookie() : [];
  const contentType = res.headers.get('content-type') || '';
  const data = contentType.includes('application/json') ? await res.json() : await res.text();
  return { status: res.status, data, cookies, headers: res.headers };
}

function parseCookies(cookieHeaders) {
  const jar = {};
  for (const c of cookieHeaders) {
    const parts = c.split(';')[0].split('=');
    if (parts.length >= 2) {
      jar[parts[0].trim()] = parts.slice(1).join('=').trim();
    }
  }
  return jar;
}

function buildCookieHeader(jar) {
  return Object.entries(jar)
    .map(([k, v]) => `${k}=${v}`)
    .join('; ');
}

async function loginUser(email, password) {
  const res = await request(`${BASE_URL}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email, password }),
  });

  if (res.status !== 200) {
    throw new Error(`Login failed for ${email}: ${res.status} ${JSON.stringify(res.data)}`);
  }

  const jar = parseCookies(res.cookies);
  return {
    user: res.data.user,
    jar,
    csrfToken: jar['csrf_token'],
    client: {
      get: (path) =>
        request(`${BASE_URL}${path}`, {
          method: 'GET',
          headers: {
            Cookie: buildCookieHeader(jar),
            ...(jar['csrf_token'] ? { 'X-CSRF-Token': jar['csrf_token'] } : {}),
          },
        }),
      post: (path, body) =>
        request(`${BASE_URL}${path}`, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            Cookie: buildCookieHeader(jar),
            ...(jar['csrf_token'] ? { 'X-CSRF-Token': jar['csrf_token'] } : {}),
          },
          body: JSON.stringify(body),
        }),
      patch: (path, body) =>
        request(`${BASE_URL}${path}`, {
          method: 'PATCH',
          headers: {
            'Content-Type': 'application/json',
            Cookie: buildCookieHeader(jar),
            ...(jar['csrf_token'] ? { 'X-CSRF-Token': jar['csrf_token'] } : {}),
          },
          body: JSON.stringify(body || {}),
        }),
    },
  };
}

async function runTests() {
  console.log('================================================================================');
  console.log(' PlateWise Token Unification & QR Code Automated Verification Suite');
  console.log('================================================================================\n');

  try {
    // -------------------------------------------------------------------------
    // Phase 1: Shared Formatter & Parser Parity
    // -------------------------------------------------------------------------
    console.log('[Phase 1] Shared Formatter & Parser Parity');

    // Original formula reference
    const originalFormatToken = (id) => {
      const num = parseInt(id, 10);
      if (isNaN(num)) return `#${id}`;
      const prefix = String.fromCharCode(65 + (Math.floor(num / 100) % 26));
      const suffix = String(num % 100).padStart(2, '0');
      return `#${prefix}-${suffix}`;
    };

    const testIds = [1, 5, 25, 42, 99, 100, 101, 111, 113, 125, 141, 200, 2500, 9999];
    let allParityMatch = true;
    for (const id of testIds) {
      const canonical = originalFormatToken(id);
      const unified = formatToken(id);
      if (canonical !== unified) {
        allParityMatch = false;
        console.error(`Mismatch for order ${id}: expected ${canonical}, got ${unified}`);
      }
    }
    assert(allParityMatch, 'Shared formatToken matches original algorithm for all test IDs', `Sample: 125 -> ${formatToken(125)}`);

    // Verify parser
    assert(parseTokenToOrderId('#B-25') === 125, 'parseTokenToOrderId parses "#B-25" -> 125');
    assert(parseTokenToOrderId('B-25') === 125, 'parseTokenToOrderId parses "B-25" -> 125');
    assert(parseTokenToOrderId('b-25') === 125, 'parseTokenToOrderId parses "b-25" (lowercase) -> 125');
    assert(parseTokenToOrderId('125') === 125, 'parseTokenToOrderId parses raw numeric "125" -> 125');
    assert(parseTokenToOrderId('#125') === 125, 'parseTokenToOrderId parses "#125" -> 125');
    assert(parseTokenToOrderId('#A-42') === 42, 'parseTokenToOrderId parses "#A-42" -> 42');
    assert(parseTokenToOrderId('A-42') === 42, 'parseTokenToOrderId parses "A-42" -> 42');
    assert(parseTokenToOrderId('INVALID') === null, 'parseTokenToOrderId returns null for invalid string');

    // -------------------------------------------------------------------------
    // Phase 2: QR Code Rendering and Decoding with jsQR
    // -------------------------------------------------------------------------
    console.log('\n[Phase 2] QR Code Rendering & Decoding with jsQR');

    const sampleToken = '#B-25';
    const decodedQR = decodeQRCodeSVG(sampleToken);
    assert(decodedQR === sampleToken, `Decoded QR payload exactly matches pickup token "${sampleToken}"`, `got "${decodedQR}"`);

    // Ensure payload contains only token and zero PII
    const hasOnlyToken = decodedQR.startsWith('#') && decodedQR.length <= 10;
    const containsNoPII = !decodedQR.includes('@') && !decodedQR.includes('student') && !decodedQR.includes('order');
    assert(hasOnlyToken && containsNoPII, 'QR code payload contains ONLY the pickup token (no student PII, name, email, or item list)');

    // -------------------------------------------------------------------------
    // Phase 3: Cross-Dashboard Token Consistency (Kitchen, Cashier, Student)
    // -------------------------------------------------------------------------
    console.log('\n[Phase 3] Cross-Dashboard Token Consistency');

    const kitchenUser = await loginUser('kitchen@platewise.campus', 'Kitchen@123');
    const cashierUser = await loginUser('cashier@platewise.campus', 'Cashier@123');
    const studentUser = await loginUser('aarav.sharma@campus.edu', 'Student@123');

    assert(kitchenUser.user.role === 'kitchen', 'Kitchen user authenticated');
    assert(cashierUser.user.role === 'cashier', 'Cashier user authenticated');
    assert(studentUser.user.role === 'student', 'Student user authenticated');

    // 3d. Student dashboard endpoint (active_order or recent_orders)
    const studentDashRes = await studentUser.client.get('/student/dashboard');
    assert(studentDashRes.status === 200, 'Student dashboard responded 200 OK');

    // Pick target order from student's active or recent orders to ensure cross-dashboard presence
    const dashTargetOrder = studentDashRes.data.active_order || (studentDashRes.data.recent_orders || [])[0] || { order_id: 141 };
    const targetOrderId = dashTargetOrder.order_id;
    const expectedToken = formatToken(targetOrderId);

    const dashRecent = (studentDashRes.data.recent_orders || []).find((o) => o.order_id === targetOrderId);
    const dashToken = dashRecent ? dashRecent.pickup_token : (studentDashRes.data.active_order?.order_id === targetOrderId ? studentDashRes.data.active_order.pickup_token : null);
    assert(dashToken === expectedToken, `Student dashboard returns token "${expectedToken}" for Order #${targetOrderId}`, `dashboard: ${dashToken}`);

    // 3a. Cashier orders endpoint
    const cashierRes = await cashierUser.client.get('/cashier/orders?date=all');
    assert(cashierRes.status === 200, 'Cashier orders endpoint responded 200 OK');
    const cashierOrder = (cashierRes.data || []).find((o) => o.order_id === targetOrderId);
    const cashierToken = cashierOrder ? cashierOrder.token : null;
    assert(cashierToken === expectedToken, `Cashier returns token "${expectedToken}" for Order #${targetOrderId}`, `cashier: ${cashierToken}`);

    // 3b. Kitchen orders endpoint
    const kitchenRes = await kitchenUser.client.get('/kitchen/orders?date=all');
    assert(kitchenRes.status === 200, 'Kitchen orders endpoint responded 200 OK');
    const kitchenOrder = (kitchenRes.data.orders || []).find((o) => o.order_id === targetOrderId);
    const kitchenToken = kitchenOrder ? kitchenOrder.token : null;
    assert(kitchenToken === expectedToken, `Kitchen returns token "${expectedToken}" for Order #${targetOrderId}`, `kitchen: ${kitchenToken}`);

    // 3c. Student orders endpoint
    const studentOrdersRes = await studentUser.client.get('/student/orders');
    assert(studentOrdersRes.status === 200, 'Student orders endpoint responded 200 OK');
    const studentOrdersList = Array.isArray(studentOrdersRes.data) ? studentOrdersRes.data : (studentOrdersRes.data.orders || []);
    const studentOrder = studentOrdersList.find((o) => o.order_id === targetOrderId);
    const studentToken = studentOrder ? studentOrder.pickup_token : null;
    assert(studentToken === expectedToken, `Student orders list returns token "${expectedToken}" for Order #${targetOrderId}`, `student: ${studentToken}`);

    // 3e. Check consistency across all dashboards
    assert(
      cashierToken === kitchenToken && kitchenToken === studentToken && studentToken === dashToken,
      'All dashboards (Kitchen, Cashier, Student Orders, Student Dashboard) return the identical canonical token string'
    );

    // -------------------------------------------------------------------------
    // Phase 4: Cashier Token Verification of Decoded QR Value & Numeric Tokens
    // -------------------------------------------------------------------------
    console.log('\n[Phase 4] Cashier Token Verification of Decoded QR Value & Numeric Tokens');

    // 4a. Decoded QR Value (#B-25 -> 125)
    const qrDecodedValue = decodeQRCodeSVG('#B-25');
    const verifyQrRes = await cashierUser.client.get(`/cashier/verify/${encodeURIComponent(qrDecodedValue)}`);
    assert(
      verifyQrRes.status === 200 && verifyQrRes.data?.order_id === 125,
      'Cashier verification accepts decoded QR string ("#B-25") and resolves to Order #125',
      `order_id: ${verifyQrRes.data?.order_id}`
    );

    // 4b. Formatted Token without hash (B-25)
    const verifyNoHashRes = await cashierUser.client.get('/cashier/verify/B-25');
    assert(
      verifyNoHashRes.status === 200 && verifyNoHashRes.data?.order_id === 125,
      'Cashier verification accepts "B-25" without "#" and resolves to Order #125'
    );

    // 4c. Raw numeric token (125)
    const verifyNumericRes = await cashierUser.client.get('/cashier/verify/125');
    assert(
      verifyNumericRes.status === 200 && verifyNumericRes.data?.order_id === 125,
      'Cashier verification accepts legacy numeric token "125" and resolves to Order #125'
    );

    // 4d. Invalid token rejection
    const verifyInvalidRes = await cashierUser.client.get('/cashier/verify/NONEXISTENT-TOKEN');
    assert(verifyInvalidRes.status === 404, 'Cashier verification returns 404 for invalid/unparseable token');

    // -------------------------------------------------------------------------
    // Phase 5: Student Order Creation, Token Return & Cashier Handover Flow
    // -------------------------------------------------------------------------
    console.log('\n[Phase 5] Student Order Creation, Token Generation & Handover Flow');

    // Log in as second student (Ananya) to avoid rapid-submission rate limits
    const studentUser2 = await loginUser('ananya.verma@campus.edu', 'Student@123');

    // Fetch an available menu item
    const [menuRows] = await pool.query('SELECT menu_item_id, price FROM menu_items WHERE is_available = 1 LIMIT 1');
    const testItem = menuRows[0];

    // Compute future date & valid slot
    const tomorrow = new Date();
    tomorrow.setDate(tomorrow.getDate() + 1);
    const testDate = tomorrow.toISOString().split('T')[0];
    const testSlot = '12:30 PM - 01:00 PM';

    // Student places an order
    const orderRes = await studentUser2.client.post('/student/orders', {
      pickup_date: testDate,
      pickup_slot: testSlot,
      payment_method: 'UPI',
      items: [{ menu_item_id: testItem.menu_item_id, quantity: 1 }],
    });

    assert(
      orderRes.status === 201 && orderRes.data?.order_id,
      'Student order placed successfully',
      `order_id: ${orderRes.data?.order_id}`
    );

    const newOrderId = orderRes.data.order_id;
    const returnedToken = orderRes.data.pickup_token;
    const expectedNewToken = formatToken(newOrderId);

    assert(
      returnedToken === expectedNewToken,
      `POST /api/student/orders returns correct formatted pickup_token ("${returnedToken}")`,
      `expected: ${expectedNewToken}`
    );

    // Render & decode QR code for the new order
    const newDecodedQR = decodeQRCodeSVG(returnedToken);
    assert(newDecodedQR === returnedToken, `QR code for new order decodes to exact token "${returnedToken}"`);

    // Cashier verifies new order via decoded QR token
    const cashierVerifyNew = await cashierUser.client.get(`/cashier/verify/${encodeURIComponent(newDecodedQR)}`);
    assert(
      cashierVerifyNew.status === 200 && cashierVerifyNew.data?.order_id === newOrderId,
      `Cashier successfully verifies new order using decoded QR token "${newDecodedQR}"`,
      `order_id: ${cashierVerifyNew.data?.order_id}, status: ${cashierVerifyNew.data?.status}`
    );

    // Transition order to Ready in DB to test handover
    await pool.query("UPDATE orders SET status = 'Ready' WHERE order_id = ?", [newOrderId]);

    // Cashier performs handover
    const handoverRes = await cashierUser.client.patch(`/cashier/orders/${newOrderId}/handover`);
    assert(
      handoverRes.status === 200 && handoverRes.data?.status === 'Collected',
      'Cashier successfully hands over Ready order -> status transitions to "Collected"',
      `new_status: ${handoverRes.data?.status}`
    );

    // Repeat handover must fail with 409
    const repeatHandoverRes = await cashierUser.client.patch(`/cashier/orders/${newOrderId}/handover`);
    assert(
      repeatHandoverRes.status === 409,
      'Repeat handover on collected order is rejected with 409 Conflict'
    );

    // Clean up created test order from DB
    await pool.query('DELETE FROM payments WHERE order_id = ?', [newOrderId]);
    await pool.query('DELETE FROM order_items WHERE order_id = ?', [newOrderId]);
    await pool.query('DELETE FROM orders WHERE order_id = ?', [newOrderId]);
    console.log(`  ✓ Cleaned up test order #${newOrderId}`);

    // Ensure order 111 is restored to 'Ready'
    await pool.query("UPDATE orders SET status = 'Ready' WHERE order_id = 111");

    console.log('\n================================================================================');
    console.log(` Test Summary: ${passedCount} Passed, ${failedCount} Failed`);
    console.log('================================================================================\n');

    process.exit(failedCount > 0 ? 1 : 0);
  } catch (error) {
    console.error('Test suite failed with error:', error);
    process.exit(1);
  }
}

runTests();
